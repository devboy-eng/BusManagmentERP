class WhatsappTemplatesController < ApplicationController
  before_action :set_template, only: [:edit, :update, :destroy, :sync_to_meta, :sync_status, :delete_from_meta]

  def index
    @templates = WhatsappTemplate.ordered
  end

  def new
    @template = WhatsappTemplate.new(language: "en", header_type: "none")
  end

  def create
    @template = current_user.whatsapp_templates.build(template_params)
    if @template.save
      redirect_to whatsapp_templates_path, notice: "Template created successfully."
    else
      render :new, status: :unprocessable_entity
    end
  end

  def edit
  end

  def update
    if @template.update(template_params)
      redirect_to whatsapp_templates_path, notice: "Template updated successfully."
    else
      render :edit, status: :unprocessable_entity
    end
  end

  def destroy
    if @template.meta_template_id.present?
      begin
        WhatsappService.new.delete_template(@template)
      rescue => e
        Rails.logger.warn("Failed to delete template from Meta: #{e.message}")
      end
    end
    @template.destroy
    redirect_to whatsapp_templates_path, notice: "Template deleted successfully."
  end

  def sync_to_meta
    unless WhatsappSetting.configured?
      redirect_to whatsapp_templates_path, alert: "Please configure WhatsApp settings first."
      return
    end

    result = WhatsappService.new.create_template(@template)
    if result[:success]
      redirect_to whatsapp_templates_path, notice: "Template submitted to Meta. Status: Pending review."
    else
      redirect_to whatsapp_templates_path, alert: "Failed to sync: #{result[:error]}"
    end
  rescue => e
    redirect_to whatsapp_templates_path, alert: "Error: #{e.message}"
  end

  def sync_status
    unless @template.meta_template_id.present?
      redirect_to whatsapp_templates_path, alert: "Template not synced to Meta yet."
      return
    end

    result = WhatsappService.new.sync_status_from_meta(@template)
    if result[:success]
      redirect_to whatsapp_templates_path, notice: "Status updated: #{result[:status]&.titleize}"
    else
      redirect_to whatsapp_templates_path, alert: "Failed to sync status: #{result[:error]}"
    end
  rescue => e
    redirect_to whatsapp_templates_path, alert: "Error: #{e.message}"
  end

  def sync_all
    unless WhatsappSetting.configured?
      redirect_to whatsapp_templates_path, alert: "Please configure WhatsApp settings first."
      return
    end

    service = WhatsappService.new
    result = service.fetch_all_templates_from_meta

    unless result[:success]
      redirect_to whatsapp_templates_path, alert: "Failed to fetch from Meta: #{result[:error]}"
      return
    end

    imported = 0
    updated = 0

    result[:templates].each do |meta_tpl|
      meta_id = meta_tpl["id"]
      name = meta_tpl["name"]
      status = meta_tpl["status"]&.downcase
      language = meta_tpl["language"]
      category = meta_tpl["category"]&.downcase
      components = meta_tpl["components"] || []

      # Extract header, body, footer from components
      header_type = "none"
      header_text = nil
      header_media_url = nil
      body_text = nil
      footer_text = nil

      components.each do |comp|
        case comp["type"]
        when "HEADER"
          fmt = comp["format"]
          header_type = fmt&.downcase || "text"
          header_text = comp["text"] if fmt == "TEXT"
          if %w[IMAGE VIDEO DOCUMENT].include?(fmt)
            header_media_url = comp.dig("example", "header_handle", 0)
          end
        when "BODY"
          body_text = comp["text"]
        when "FOOTER"
          footer_text = comp["text"]
        end
      end

      # If header is "text" but no text found, set to "none"
      header_type = "none" if header_type == "text" && header_text.blank?

      # Find existing template by meta_template_id or create new
      template = WhatsappTemplate.find_by(meta_template_id: meta_id)

      # Authentication templates have auto-generated body by Meta
      body_text = "(Auto-generated by Meta)" if body_text.blank? && category == "authentication"
      body_text ||= ""

      if template
        template.update!(
          status: status,
          language: language,
          category: category,
          body: body_text.presence || template.body,
          header_type: header_type,
          header_text: header_text,
          footer: footer_text
        )
        updated += 1
      else
        WhatsappTemplate.create!(
          name: name,
          meta_template_id: meta_id,
          status: status,
          language: language,
          category: category,
          body: body_text,
          header_type: header_type,
          header_text: header_text,
          header_media_url: header_media_url,
          footer: footer_text,
          user: current_user
        )
        imported += 1
      end
    end

    parts = []
    parts << "#{imported} template(s) imported" if imported > 0
    parts << "#{updated} template(s) updated" if updated > 0
    parts << "No templates found on Meta" if imported == 0 && updated == 0

    redirect_to whatsapp_templates_path, notice: parts.join(", ") + "."
  rescue => e
    redirect_to whatsapp_templates_path, alert: "Error: #{e.message}"
  end

  def delete_from_meta
    unless @template.meta_template_id.present?
      redirect_to whatsapp_templates_path, alert: "Template not synced to Meta."
      return
    end

    result = WhatsappService.new.delete_template(@template)
    if result[:success]
      redirect_to whatsapp_templates_path, notice: "Template removed from Meta."
    else
      redirect_to whatsapp_templates_path, alert: "Failed to delete from Meta: #{result[:error]}"
    end
  rescue => e
    redirect_to whatsapp_templates_path, alert: "Error: #{e.message}"
  end

  private

  def set_template
    @template = WhatsappTemplate.find(params[:id])
  end

  def template_params
    permitted = params.require(:whatsapp_template).permit(:name, :body, :category, :language, :header_type, :header_text, :header_media_url, :footer, :template_type, :carousel_cards)
    # Parse carousel_cards from form JSON string
    if permitted[:carousel_cards].present? && permitted[:carousel_cards].is_a?(String)
      begin
        JSON.parse(permitted[:carousel_cards])
      rescue JSON::ParserError
        permitted[:carousel_cards] = "[]"
      end
    end
    permitted
  end
end
